class Solution {
public:
    long long countCommas(long long n) {
        long long cnt=0;
        if(n < 1000) return 0;
        if(n <=999999) return n - 999;
        if(n <=999999999) return ((n - 999999)*2) + (999999 - 999);
        if(n <= 999999999999) return ((n - 999999999)*3) + ((999999999 - 999999)*2) + (999999 - 999);
        if(n <= 999999999999999) return ((n-999999999999)*4) + ((999999999999 - 999999999)*3) + ((999999999 - 999999)*2) + (999999 - 999);
        if(n == 1e15) return 1 + ((n-999999999999)*4) + ((999999999999 - 999999999)*3) + ((999999999 - 999999)*2) + (999999 - 999);
        return cnt;
    }
};